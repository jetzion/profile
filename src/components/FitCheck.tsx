"use client";

import { FormEvent, useState } from "react";
import { Markdown } from "@/components/Markdown";
import { site } from "@/content/site";
import { streamTwin } from "@/lib/stream";

/** Paste a job description, stream back a role-fit analysis, and print it. */
export function FitCheck() {
  const [jd, setJd] = useState("");
  const [result, setResult] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function onSubmit(event: FormEvent) {
    event.preventDefault();
    if (busy) return;
    setBusy(true);
    setError(null);
    setResult("");
    try {
      await streamTwin("/api/fit", { jd }, setResult);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Something went wrong.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="space-y-10">
      <form onSubmit={onSubmit} className="print:hidden">
        <label htmlFor="jd" className="eyebrow mb-3 block">
          Job description
        </label>
        <textarea
          id="jd"
          value={jd}
          onChange={(event) => setJd(event.target.value)}
          rows={10}
          maxLength={12000}
          placeholder="Paste the full job description: title, responsibilities, requirements."
          className="w-full resize-y border border-brass/50 bg-(--input-bg) px-5 py-4 text-sm leading-relaxed text-ink caret-accent shadow-[inset_3px_0_0_0_var(--brass)] outline-none placeholder:text-muted focus:border-accent focus:shadow-[inset_3px_0_0_0_var(--accent)] md:text-base"
        />
        <div className="mt-4 flex flex-wrap items-center gap-4">
          <button
            type="submit"
            disabled={busy || jd.trim().length < 80}
            className="bg-accent px-6 py-3 text-sm font-medium tracking-wide text-bg transition-opacity hover:opacity-90 disabled:opacity-30"
          >
            {busy ? "Analyzing…" : "Analyze fit"}
          </button>
          <span className="text-xs text-faint">
            {jd.length.toLocaleString()} / 12,000 characters · Nothing is stored.
          </span>
        </div>
        {error ? <p className="mt-4 text-sm text-brass">{error}</p> : null}
      </form>

      {result ? (
        <section className="border border-line bg-bg-2 p-6 md:p-10 print:border-0 print:p-0">
          <div className="mb-8 flex flex-wrap items-start justify-between gap-4 border-b border-line pb-6">
            <div>
              <p className="eyebrow">Role fit analysis</p>
              <p className="font-display mt-2 text-3xl font-semibold">{site.name}</p>
              <p className="mt-1 text-sm text-muted">
                {site.title} · {site.email} · {site.linkedin.replace("https://www.", "")}
              </p>
            </div>
            {!busy ? (
              <button
                type="button"
                onClick={() => window.print()}
                className="border border-line-strong px-4 py-2 text-sm hover:border-accent print:hidden"
              >
                Save as PDF
              </button>
            ) : null}
          </div>
          <Markdown>{result}</Markdown>
          <p className="mt-10 border-t border-line pt-4 text-xs text-faint">
            Generated by Jack’s Digital Twin from his public career record. Verify
            details in conversation.
          </p>
        </section>
      ) : null}
    </div>
  );
}
